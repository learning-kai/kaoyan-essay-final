/** 查询某个句子被哪些模板引用 */
export function getTemplatesUsingSentence(sentenceId: string): Template[] {
  return TEMPLATES.filter((t) => t.sentenceIds.includes(sentenceId));
}

/** 将模板拼装为完整英文（槽位替换为 [中文标签]），用于核对原文 */
export function renderTemplateWithBracketLabels(
  template: Template,
  slotLabels: Record<string, string>
): string {
  const getText = (id: string) => {
    const s = SENTENCES[id];
    return s.en.replace(/\{\{(\w+)\}\}/g, (_, key: string) => `[${slotLabels[key] ?? key}]`);
  };

  const heading = getText(template.sentenceIds[0]);
  const para1 = `${getText(template.sentenceIds[1])} ${getText(template.sentenceIds[2])}`;
  const bodyIds = template.sentenceIds.slice(3, -2);
  const para2 = bodyIds.map(getText).join(' ');
  const closing = getText(template.sentenceIds[template.sentenceIds.length - 2]);
  const signoff = getText(template.sentenceIds[template.sentenceIds.length - 1]);

  return [heading, para1, para2, closing, signoff].join('\n\n');
}
