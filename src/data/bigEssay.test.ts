import { describe, expect, it } from 'vitest';
import { Rating } from 'ts-fsrs';
import {
  checkPlanSheet,
  checkPlanVarBenefit,
  checkPlanVarDO,
  checkPlanVarX,
  getBigEssayWordCountStatus,
  gradeBigEssayAlignment,
} from '../core/grader';
import { createInitialCard, interleaveQueue, reviewCard } from '../core/scheduler';
import {
  BIG_SENTENCES,
  BIG_SENTENCE_MAP,
  MATERIAL_PACKS,
  PLAN_VARS,
  renderFullBigEssay,
} from './bigEssay';
import { generateRandomChart } from './bigChart';
import { migrateProgressCards, serializeCard } from '../store/useProgress';

/**
 * 附录 A 11 句逐字黄金基准（来源于 大作文模块_开发提示词.md 附录 A）
 */
const APPENDIX_A_VERBATIM: { id: string; en: string }[] = [
  {
    id: 'big.p1.s1',
    en: 'The picture presents a vivid scene in which {{PIC}}.',
  },
  {
    id: 'big.p1.s2',
    en: 'The deeper issue revealed by the drawing lies in the value and impact of {{X}} in modern society.',
  },
  {
    id: 'big.p1.s3',
    en: 'When its positive potential is properly realized, {{X}} can help people determine through practice which beliefs deserve to be upheld and which aspects require adjustment, thereby enhancing the accuracy of their judgment.',
  },
  {
    id: 'big.p2.s1',
    en: '{{X}} brings {{G|people}} not only {{B1}} but also {{B2}}.',
  },
  {
    id: 'big.p2.s2',
    en: 'As society develops and technology advances, {{X}}, once rendered {{OLD|inaccessible}} by {{LIMIT|high costs and limited resources}}, has become increasingly {{NEW|accessible}}, enabling people to {{DO}}.',
  },
  {
    id: 'big.p2.s3',
    en: 'Moreover, the sustained {{ATT|attention}} and extensive {{DIS|discussion}} generated by {{MEDIA|social media}} have brought {{X}} into the public consciousness and further strengthened its {{EFFECT|influence}}.',
  },
  {
    id: 'big.p2.s4',
    en: "Therefore, changes in {{X}} reflect not only {{R1|social progress}} but also {{R2|people's growing pursuit of a better life}}.",
  },
  {
    id: 'big.p3.s1',
    en: 'What ultimately determines the value of {{X}} is not {{SURF|its popularity}}, but whether {{CORE|it is used wisely and responsibly}}.',
  },
  {
    id: 'big.p3.s2',
    en: 'Society should {{ACT|provide more support and guidance}}, addressing {{PROB|its potential problems}} while preserving {{KEEP|its core value}}.',
  },
  {
    id: 'big.p3.s3',
    en: 'Individuals should treat {{X}} rationally, neither {{N1|blindly following it}} nor {{N2|completely rejecting it}}.',
  },
  {
    id: 'big.p3.s4',
    en: 'Only in this way can {{X}} truly contribute to the well-being of individuals and the progress of society.',
  },
];

describe('大作文模块：九项验收清单全量校验', () => {
  it('1. 附录 A 全部 11 句和代码数据逐字一致（零篡改）', () => {
    expect(BIG_SENTENCES).toHaveLength(11);
    for (const expected of APPENDIX_A_VERBATIM) {
      const actual = BIG_SENTENCE_MAP[expected.id];
      expect(actual, `缺少句子 ${expected.id}`).toBeDefined();
      expect(actual.en).toBe(expected.en);
    }
    expect(BIG_SENTENCE_MAP['big.p2.s4'].optional).toBe(true);
    expect(BIG_SENTENCE_MAP['big.p3.s4'].smallEssayLink).toContain('Only in this way');
  });

  it('2. 小作文原有进度在 v3 -> v4 迁移后完整保留并补齐 deck 字段', () => {
    const t = new Date('2026-11-23T08:00:00Z');
    const c1 = serializeCard(reviewCard(createInitialCard(t), Rating.Good, t));
    const c2 = serializeCard(reviewCard(createInitialCard(t), Rating.Easy, t));
    // Legacy v3 record has no deck field
    delete c1.deck;
    delete c2.deck;

    const migrated = migrateProgressCards({
      'shared.closing': c1,
      'suggest.body1': c2,
      'big.p1.s1': serializeCard(createInitialCard(t)),
    });

    expect(Object.keys(migrated).sort()).toEqual([
      'big.p1.s1',
      'shared.closing',
      'suggest.body1',
    ]);
    expect(migrated['shared.closing'].deck).toBe('small');
    expect(migrated['suggest.body1'].deck).toBe('small');
    expect(migrated['big.p1.s1'].deck).toBe('big');
    expect(migrated['shared.closing'].stability).toBe(c1.stability);
    expect(migrated['suggest.body1'].reps).toBe(c2.reps);
  });

  it('3. 全部 10 个素材包代入模板（去掉可选句 P2.S4）均在 160–220 词之间且无单复数/词性错误', () => {
    expect(MATERIAL_PACKS).toHaveLength(10);

    for (const pack of MATERIAL_PACKS) {
      expect(pack.picExamples.length).toBeGreaterThanOrEqual(2);
      expect(
        checkPlanVarX(pack.vars.X).ok,
        `素材包 ${pack.id} 的 X="${pack.vars.X}" 未通过单数/不可数检查`
      ).toBe(true);
      expect(
        checkPlanVarBenefit(pack.vars.B1, 'B1').ok,
        `素材包 ${pack.id} 的 B1="${pack.vars.B1}" 未通过名词短语检查`
      ).toBe(true);
      expect(
        checkPlanVarBenefit(pack.vars.B2, 'B2').ok,
        `素材包 ${pack.id} 的 B2="${pack.vars.B2}" 未通过名词短语检查`
      ).toBe(true);
      expect(
        checkPlanVarDO(pack.vars.DO).ok,
        `素材包 ${pack.id} 的 DO="${pack.vars.DO}" 未通过动词原形检查`
      ).toBe(true);

      for (const [idx, pic] of pack.picExamples.entries()) {
        const rendered = renderFullBigEssay(
          { ...pack.vars, PIC: pic },
          { includeOptionalP2S4: false }
        );
        expect(
          rendered.wordCount,
          `素材包 ${pack.id} 样例 ${idx + 1} 字数 ${rendered.wordCount} 超出 160–220 区间`
        ).toBeGreaterThanOrEqual(160);
        expect(
          rendered.wordCount,
          `素材包 ${pack.id} 样例 ${idx + 1} 字数 ${rendered.wordCount} 超出 160–220 区间`
        ).toBeLessThanOrEqual(220);
        expect(rendered.fullText).not.toMatch(/\{\{|\}\}|\[[A-Z0-9_]+\]/);
      }
    }
  });

  it('4. 规划卡 X 填 online courses 时，提示改用单数或不可数名词', () => {
    const res = checkPlanVarX('online courses');
    expect(res.ok).toBe(false);
    expect(res.hint).toMatch(/单数|不可数/);

    const okRes = checkPlanVarX('online learning');
    expect(okRes.ok).toBe(true);

    // Whitelisted singular -s nouns must NOT false-trigger
    expect(checkPlanVarX('physical fitness').ok).toBe(true);
    expect(checkPlanVarX('social progress').ok).toBe(true);

    const sheet = checkPlanSheet({
      X: 'online courses',
      PIC: 'a student is studying online at home',
      B1: 'greater flexibility',
      B2: 'broader knowledge',
      DO: 'learn anytime and anywhere',
    });
    expect(sheet.grammarPassed).toBe(false);
    expect(sheet.fieldHints.X).toMatch(/单数|不可数/);
  });

  it('5. 不改任何默认值、只填 4 个必填项（X / PIC / B1&B2 / DO），也能生成一篇完整文章', () => {
    expect(PLAN_VARS.filter((v) => !v.required).every((v) => Boolean(v.defaultValue))).toBe(
      true
    );

    const rendered = renderFullBigEssay(
      {
        X: 'lifelong learning',
        PIC: 'a young office worker is reading books in the evening',
        B1: 'continuous self-improvement',
        B2: 'career resilience',
        DO: 'adapt to rapid changes with confidence',
      },
      { includeOptionalP2S4: false }
    );

    expect(rendered.paragraphs).toHaveLength(3);
    expect(rendered.wordCount).toBeGreaterThanOrEqual(160);
    expect(rendered.wordCount).toBeLessThanOrEqual(220);
    expect(rendered.fullText).not.toMatch(/\{\{|\}\}|\[[A-Z0-9_]+\]/);
    // Verify optional defaults were automatically filled
    expect(rendered.fullText).toContain('brings people not only');
    expect(rendered.fullText).toContain('once rendered inaccessible by high costs and limited resources');
    expect(rendered.fullText).toContain('generated by social media');
    expect(rendered.fullText).toContain('blindly following it');
  });

  it('6. 模板对齐判分能识别漏掉的固定片段并定位到第几句，且兼容 15 词长槽位与单复数检查', () => {
    const baseVars = {
      X: 'traditional culture',
      PIC: 'an elderly artisan is patiently teaching several curious young children how to fold intricate red paper-cuttings', // 16-word long slot
      G: 'young people',
      B1: 'a sense of cultural identity',
      B2: 'spiritual enrichment',
      LIMIT: 'limited channels of communication',
      DO: 'appreciate the charm of history in daily life',
    };

    const fullEssay = renderFullBigEssay(baseVars, { includeOptionalP2S4: false });
    const perfectGrade = gradeBigEssayAlignment(fullEssay.fullText, {
      includeOptionalP2S4: false,
      planVars: baseVars,
    });
    expect(perfectGrade.fixedAccuracy).toBeGreaterThanOrEqual(0.95);
    expect(perfectGrade.missingFragments).toHaveLength(0);
    expect(perfectGrade.grammarHints).toHaveLength(0);

    // Drop fixed phrase from sentence #9 (P3.S3: "neither ... nor ...")
    const droppedText = fullEssay.fullText.replace(
      'Individuals should treat traditional culture rationally, neither blindly following it nor completely rejecting it.',
      'Individuals should treat traditional culture rationally.'
    );
    const missingGrade = gradeBigEssayAlignment(droppedText, {
      includeOptionalP2S4: false,
      planVars: baseVars,
    });
    expect(missingGrade.missingFragments.length).toBeGreaterThan(0);
    // P3.S3 is sentence #9 when P2.S4 is omitted
    const hit = missingGrade.missingFragments.find((m) => m.sentenceId === 'big.p3.s3');
    expect(hit).toBeDefined();
    expect(hit!.sentenceNumber).toBe(9);

    // Plural X triggers grammar hint (both via planVars and auto-extracted from essay text)
    const pluralGrade = gradeBigEssayAlignment(fullEssay.fullText, {
      includeOptionalP2S4: false,
      planVars: { X: 'online courses' },
    });
    expect(pluralGrade.grammarHints.some((h) => h.includes('复数'))).toBe(true);

    const pluralTextEssay = renderFullBigEssay(
      { ...baseVars, X: 'online courses' },
      { includeOptionalP2S4: false }
    );
    const autoExtractGrade = gradeBigEssayAlignment(pluralTextEssay.fullText, {
      includeOptionalP2S4: false,
    });
    expect(autoExtractGrade.grammarHints.some((h) => h.includes('复数'))).toBe(true);

    // Word count status boundaries
    expect(getBigEssayWordCountStatus(180)).toBe('ok');
    expect(getBigEssayWordCountStatus(155)).toBe('warn');
    expect(getBigEssayWordCountStatus(210)).toBe('warn');
    expect(getBigEssayWordCountStatus(140)).toBe('err');
    expect(getBigEssayWordCountStatus(230)).toBe('err');
  });

  it('7. 随机饼图的数据百分比合计严格等于 100%', () => {
    for (let i = 0; i < 20; i++) {
      const pie = generateRandomChart('pie');
      expect(pie.nature).toBe('static');
      expect(pie.staticData).toBeDefined();
      const sum = pie.staticData!.reduce((acc, d) => acc + d.value, 0);
      expect(sum).toBe(100);
    }
    const bar = generateRandomChart('bar');
    expect(bar.staticData?.length).toBeGreaterThanOrEqual(4);
    const line = generateRandomChart('line');
    expect(line.dynamicData?.length).toBeGreaterThanOrEqual(4);
  });

  it('8. 复习队列交错调度：大作文与小作文卡片混排时交替出现', () => {
    const mixed = interleaveQueue([
      'suggest.body1',
      'suggest.body2',
      'invite.body1',
      'big.p1.s1',
      'big.p1.s2',
      'big.p2.s1',
    ]);
    expect(mixed).toHaveLength(6);
    const decks = mixed.map((id) => (id.startsWith('big.') ? 'big' : 'small'));
    // Adjacent cards should alternate between small and big
    for (let i = 1; i < decks.length; i++) {
      expect(decks[i]).not.toBe(decks[i - 1]);
    }
  });
});
